"""Write results/RESULTS.md from the measured Bamboogle summaries and VeRL metrics."""

from __future__ import annotations

import json
from pathlib import Path


HERE = Path(__file__).parent
RESULTS = HERE / "results"
VAL_KEY = "val-core/searchR1_nq_hotpotqa/acc/mean@1"
BASELINES = [
    ("Direct inference (Qwen2.5-3B-Instruct)", "qwen25_3b_direct", "0.024 (3/125)"),
    ("Qwen2.5-3B-Instruct + search tool, untrained", "qwen25_3b_base_tool", "n/a"),
    ("Published Search-R1 PPO checkpoint (full FT)", "searchr1_published_ppo", "0.264 (33/125)"),
    ("Published Search-R1 GRPO checkpoint (full FT)", "searchr1_published_grpo", "0.232 (29/125)"),
]


def load_summary(name: str) -> dict | None:
    path = RESULTS / "bamboogle" / f"{name}.summary.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def load_metrics(run: str) -> list[dict]:
    path = RESULTS / "runs" / run / "metrics.jsonl"
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()] if path.exists() else []


def mean(rows: list[dict], key: str) -> float | None:
    values = [row["data"][key] for row in rows if key in row["data"]]
    return sum(values) / len(values) if values else None


def fmt(value: float | None, digits: int = 3) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def main() -> None:
    lines = ["# Measured results (generated by summarize_results.py)", ""]
    lines += ["## Bamboogle (125 questions, greedy decoding, wiki-18 E5 top-3)", ""]
    lines += ["| Method | Protocol | EM | Correct | Mean searches | Paper reference |", "| --- | --- | ---: | ---: | ---: | --- |"]
    for label, name, paper in BASELINES:
        summary = load_summary(name)
        if summary:
            lines.append(
                f"| {label} | {summary['mode']} | {summary['exact_match']:.3f} | {summary['correct']}/125 | "
                f"{summary['mean_search_calls']:.2f} | {paper} |"
            )
    for run, paper in (("grpo-main", "0.232 (29/125), full FT"), ("ppo-main", "0.264 (33/125), full FT")):
        steps = sorted(
            int(path.name.split("_step")[1].split(".")[0])
            for path in (RESULTS / "bamboogle").glob(f"{run}_step*.summary.json")
        )
        for step in steps:
            summary = load_summary(f"{run}_step{step}")
            lines.append(
                f"| Ours: LoRA {run.split('-')[0].upper()}, step {step} | tool | {summary['exact_match']:.3f} | "
                f"{summary['correct']}/125 | {summary['mean_search_calls']:.2f} | {paper if step == steps[-1] else ''} |"
            )

    lines += ["", "## Training runs (NQ + HotpotQA, 64 prompts x 5 rollouts per step)", ""]
    lines += [
        "| Run | Last logged step | Val EM @ step (512 in-domain questions) | Train reward, first 10 steps | Train reward, last 10 steps | KL loss, last 10 | Mean s/step |",
        "| --- | ---: | --- | ---: | ---: | ---: | ---: |",
    ]
    for run in ("grpo-main", "ppo-main"):
        rows = load_metrics(run)
        train = [row for row in rows if "critic/score/mean" in row["data"]]
        if not train:
            continue
        val = ", ".join(f"{row['step']}: {row['data'][VAL_KEY]:.3f}" for row in rows if VAL_KEY in row["data"])
        lines.append(
            f"| {run} | {train[-1]['step']} | {val} | {fmt(mean(train[:10], 'critic/score/mean'))} | "
            f"{fmt(mean(train[-10:], 'critic/score/mean'))} | {fmt(mean(train[-10:], 'actor/kl_loss'), 4)} | "
            f"{fmt(mean(train, 'timing_s/step'), 1)} |"
        )
    (RESULTS / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
